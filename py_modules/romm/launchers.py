"""Per-ROM launch scripts that Steam shortcuts point at.

  ~/.local/share/romm-decky/launch/<rom_id>.sh

Each holds the resolved emulator command line. Shortcuts never change when the
emulator choice does; the plugin just rewrites the script. Steam's launch
options stay free for the user and are passed through as "$@".
"""

from __future__ import annotations

import os
import shlex


def launch_dir(home: str) -> str:
    return os.path.join(home, ".local", "share", "romm-decky", "launch")


def script_path(home: str, rom_id) -> str:
    return os.path.join(launch_dir(home), f"{int(rom_id)}.sh")


def write(home: str, rom_id, title: str, argv: list[str]) -> str:
    path = script_path(home, rom_id)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    safe_title = " ".join((title or "").split())  # no newlines in the comment
    body = (
        "#!/bin/sh\n"
        f"# romm-decky launcher: {safe_title} (RomM ROM {int(rom_id)}). Regenerated by the plugin.\n"
        f"exec {shlex.join(argv)} \"$@\"\n"
    )
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(body)
    os.chmod(tmp, 0o755)
    os.replace(tmp, path)
    return path


def remove(home: str, rom_id) -> None:
    try:
        os.remove(script_path(home, rom_id))
    except FileNotFoundError:
        pass
